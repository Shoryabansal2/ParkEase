CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(64) PRIMARY KEY, name VARCHAR(100) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE, passwordHash VARCHAR(255) NOT NULL,
  role ENUM('DRIVER','OPERATOR','ADMIN') NOT NULL DEFAULT 'DRIVER', vehicle VARCHAR(30) NOT NULL DEFAULT '',
  membershipTier VARCHAR(16) NOT NULL DEFAULT 'STANDARD', membershipExpiresAt VARCHAR(30) NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', sessionVersion INT NOT NULL DEFAULT 0, createdAt VARCHAR(30) NULL,
  operatorTier VARCHAR(16) NOT NULL DEFAULT 'STANDARD', operatorExpiresAt VARCHAR(30) NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS facilities (
  id VARCHAR(64) PRIMARY KEY, name VARCHAR(150) NOT NULL, address VARCHAR(255) NOT NULL,
  lat DOUBLE NOT NULL, lng DOUBLE NOT NULL, rate DECIMAL(10,2) NOT NULL,
  rating DECIMAL(2,1) NOT NULL, covered BOOLEAN NOT NULL, ev BOOLEAN NOT NULL,
  status ENUM('APPROVED','PENDING','SUSPENDED','REJECTED') NOT NULL,
  operatorId VARCHAR(64) NOT NULL, tag VARCHAR(50) NOT NULL,
  distance VARCHAR(10) NOT NULL, image VARCHAR(30) NOT NULL, photoUrl VARCHAR(255) NULL,
  FOREIGN KEY (operatorId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS slots (
  id VARCHAR(64) PRIMARY KEY, facilityId VARCHAR(64) NOT NULL,
  label VARCHAR(10) NOT NULL, vehicleType ENUM('CAR','BIKE','EV') NOT NULL,
  blocked BOOLEAN NOT NULL DEFAULT FALSE,
  FOREIGN KEY (facilityId) REFERENCES facilities(id), UNIQUE(facilityId,label)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS bookings (
  id VARCHAR(64) PRIMARY KEY, userId VARCHAR(64) NOT NULL,
  facilityId VARCHAR(64) NOT NULL, slotId VARCHAR(64) NOT NULL,
  vehicle VARCHAR(30) NOT NULL, startAt VARCHAR(30) NOT NULL, endAt VARCHAR(30) NOT NULL,
  total DECIMAL(10,2) NOT NULL, status ENUM('CONFIRMED','ACTIVE','COMPLETED','CANCELLED') NOT NULL,
  paymentStatus VARCHAR(30) NOT NULL, createdAt VARCHAR(30) NOT NULL,
  checkedInAt VARCHAR(30) NULL, checkedOutAt VARCHAR(30) NULL,
  membershipTier VARCHAR(16) NOT NULL DEFAULT 'STANDARD', baseTotal DECIMAL(10,2) NULL,
  discountAmount DECIMAL(10,2) NOT NULL DEFAULT 0, convenienceFee DECIMAL(10,2) NOT NULL DEFAULT 0, pricingSnapshot TEXT NULL,
  FOREIGN KEY (userId) REFERENCES users(id), FOREIGN KEY (facilityId) REFERENCES facilities(id),
  FOREIGN KEY (slotId) REFERENCES slots(id), INDEX booking_availability(slotId,status,startAt,endAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS auditLogs (
  id VARCHAR(64) PRIMARY KEY, actorId VARCHAR(64) NOT NULL, targetId VARCHAR(64) NOT NULL,
  action VARCHAR(40) NOT NULL, changes TEXT NOT NULL, reason VARCHAR(300) NOT NULL, createdAt VARCHAR(30) NOT NULL,
  FOREIGN KEY (actorId) REFERENCES users(id), FOREIGN KEY (targetId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS evAlerts (
  id VARCHAR(64) PRIMARY KEY, userId VARCHAR(64) NOT NULL, facilityId VARCHAR(64) NOT NULL,
  startAt VARCHAR(30) NOT NULL, endAt VARCHAR(30) NOT NULL, createdAt VARCHAR(30) NOT NULL,
  FOREIGN KEY (userId) REFERENCES users(id), FOREIGN KEY (facilityId) REFERENCES facilities(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS supportTickets (
  id VARCHAR(64) PRIMARY KEY, userId VARCHAR(64) NOT NULL, subject VARCHAR(120) NOT NULL,
  message VARCHAR(2000) NOT NULL, priority VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'OPEN', createdAt VARCHAR(30) NOT NULL,
  FOREIGN KEY (userId) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
  id VARCHAR(64) PRIMARY KEY, userId VARCHAR(64) NOT NULL,
  purpose VARCHAR(20) NOT NULL, amount DECIMAL(10,2) NOT NULL,
  method VARCHAR(10) NOT NULL, status VARCHAR(30) NOT NULL,
  bookingId VARCHAR(64) NULL, createdAt VARCHAR(30) NOT NULL,
  FOREIGN KEY (userId) REFERENCES users(id), INDEX payment_booking(bookingId)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS pricingRules (
  id VARCHAR(64) PRIMARY KEY, facilityId VARCHAR(64) NOT NULL,
  name VARCHAR(80) NOT NULL, days VARCHAR(30) NOT NULL,
  startMinute INT NOT NULL, endMinute INT NOT NULL, rate DECIMAL(10,2) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE, createdAt VARCHAR(30) NOT NULL,
  FOREIGN KEY (facilityId) REFERENCES facilities(id), INDEX pricing_facility(facilityId,enabled)
) ENGINE=InnoDB;
